import path from 'node:path';
import { chromium } from 'playwright-core';
import { WEB, findChromium, startServer } from '../../tools/browser';
const server = await startServer(0);
const browser = await chromium.launch({ executablePath: findChromium(), args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errs: string[] = [];
page.on('pageerror', (e) => errs.push(String(e)));
page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
await page.goto(server.url + '?game=mg1801&auto=1&fast=1&mute=1&seed=7&com=1111');
await page.waitForFunction(() => (window as any).__mpj?.stage === 'running', null, { timeout: 120000 });
await page.evaluate(() => (window as any).__mpj.hold(700));
await page.waitForFunction(() => (window as any).__mpj.frame >= 700, null, { timeout: 600000 });
const box = (await page.locator('canvas.jw-gl').boundingBox())!;
const shot = (n: string) => page.screenshot({ path: path.join(WEB, 'test', 'out', `freecam_${n}.png`), clip: box });
await page.waitForTimeout(800); await shot('0_orig');
await page.click('text=자유 카메라');
const cx = box.x + box.width / 2, cy = box.y + box.height / 2;
await page.mouse.move(cx, cy); await page.mouse.down(); await page.mouse.move(cx + 250, cy - 60, { steps: 12 }); await page.mouse.up();
await page.waitForTimeout(1500); await shot('1_rotate');
await page.mouse.move(cx, cy); await page.mouse.wheel(0, -600);
await page.waitForTimeout(1500); await shot('2_zoom');
await page.click('text=원본 카메라');
await page.waitForTimeout(1000); await shot('3_back');
console.log('errors', errs);
await browser.close(); await server.close();
